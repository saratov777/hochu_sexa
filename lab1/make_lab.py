def figure(doc, n, caption):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    pf = p.paragraph_format
    pf.first_line_indent = Cm(0)
    pf.line_spacing = 1.0
    pf.space_before = Pt(6)
    pf.keep_with_next = True
    p.add_run().add_picture(os.path.join(IMG, f"fig{n}.png"), width=Cm(15))
    c = para(doc, f"Рисунок {n} – {caption}", align="center", indent=False)
    c.paragraph_format.line_spacing = 1.0
    c.paragraph_format.space_after = Pt(10)
    c.paragraph_format.space_before = Pt(4)


