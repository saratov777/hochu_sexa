def page_map(pdf):
    """Physical page of each contents entry in the rendered PDF."""
    out = {}
    npages = int(re.search(r"Pages:\s+(\d+)", subprocess.run(
        ["pdfinfo", pdf], capture_output=True, text=True).stdout).group(1))
    texts = [subprocess.run(["pdftotext", "-f", str(i), "-l", str(i), "-layout", pdf, "-"],
                            capture_output=True, text=True).stdout for i in range(1, npages + 1)]
    norm = lambda s: re.sub(r"\s+", " ", s)
    start = next((i for i, t in enumerate(texts) if "СОДЕРЖАНИЕ" in t), 0) + 1
    for lvl, h in HEADINGS:
        key = norm(h)[:38]
        for i in range(start, len(texts)):
            if key in norm(texts[i]):
                out[h] = i + 1
                start = i       # headings appear in order
                break
    return out, npages


def render_pdf():
    os.makedirs(os.path.join(HERE, "build"), exist_ok=True)
    subprocess.run(["soffice", "--headless", "--convert-to", "pdf", "--outdir",
                    os.path.join(HERE, "build"), OUT], check=True, capture_output=True, timeout=240)
    return os.path.join(HERE, "build", os.path.basename(OUT).replace(".docx", ".pdf"))


