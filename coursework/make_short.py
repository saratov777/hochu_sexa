"""Краткая версия (~5 страниц): Oil_Refinery_Automated_System_Security.docx."""
import os, re, subprocess, sys
from docx import Document
from docx.shared import Cm, Pt

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from docx_kit import *  # noqa: F401,F403

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "Oil_Refinery_Automated_System_Security.docx")


def build():
    doc = Document()
    setup(doc)
    P = lambda t, **k: para(doc, t, **k)
    H1 = lambda t: doc.add_heading(t, level=1)

    # ------------------------------------------------------------ титульный лист
    for _ in range(9):
        P("", indent=False)
    P("ПРАКТИЧЕСКАЯ РАБОТА", align="center", indent=False, bold=True, size=16)
    P("Тема № 7", align="center", indent=False, bold=True)
    for _ in range(8):
        P("", indent=False)
    P("Выполнил: Молодых И.А.", align="right", indent=False)
    P("Группа: 3ИС9", align="right", indent=False)
    page_break(doc)

    # ------------------------------------------------------------------ 1
    H1("1 АС нефтеперерабатывающей компании")
    P("**Автоматизированная система нефтеперерабатывающего завода (АС НПЗ)** — корпоративная "
      "система для хранения, обработки и передачи информации о производственной, технической, "
      "финансовой и кадровой деятельности предприятия. Основные задачи: мониторинг работы "
      "установок по данным архива АСУ ТП (только чтение); планирование и согласование заданий на "
      "технологический режим; учёт нефти, нефтепродуктов и их качества; техническое обслуживание и "
      "ремонт оборудования; кадровый учёт; финансовые операции; внутренний документооборот.")
    P("Корпоративная АС **не тождественна** АСУ ТП, которая непосредственно управляет "
      "установками. Данные АСУ ТП поступают в АС через демилитаризованную зону (DMZ) только "
      "«снизу вверх», управление процессом из корпоративной сети невозможно. Объектом "
      "классификации в работе является корпоративная АС (ERP, MES, ТОиР, СЭД, кадры).")

    # ------------------------------------------------------------------ 2
    H1("2 Сведения, обрабатываемые АС")
    caption_table(doc, "Таблица 1 – Категории информации АС НПЗ")
    data_table(doc, ["Информация", "Примеры", "Уровень доступа"], [
        ["Открытая", "Ассортимент продукции, годовой отчёт", "открытая"],
        ["Служебная", "Приказы, графики смен, инструкции", "служебная"],
        ["Производственная документация", "Технологические регламенты, режимные карты", "служебная"],
        ["Технологические параметры", "Температура, давление, расход (из АСУ ТП)",
         "служебная, важна целостность"],
        ["Промышленная безопасность", "Планы ликвидации аварий, наряды-допуски", "служебная"],
        ["Оборудование", "Паспорта, графики ремонтов, дефекты", "служебная"],
        ["Финансовая информация", "Бухгалтерия, платежи, бюджеты", "конфиденциальная"],
        ["Персональные данные", "ФИО, паспорт, СНИЛС, зарплата работников", "конфиденциальная"],
        ["Коммерческая тайна", "Цены договоров, себестоимость, рецептуры топлив", "коммерческая тайна"],
    ], widths=[5.0, 7.3, 4.2], size=11)
    P("В АС одновременно присутствует **информация разных уровней конфиденциальности**. "
      "Сведения, составляющие государственную тайну, не обрабатываются: коммерческая тайна и "
      "персональные данные государственной тайной не являются.")

    # ------------------------------------------------------------------ 3
    H1("3 Субъекты доступа и матрица доступа")
    d = Diagram(20, size=10)
    d.row("box", ("box", 6, 13, "**АС НПЗ**"))
    d.row("line", ("v", 10))
    d.row("line", ("h", 2, 18), *[("v", b) for b in (2, 6, 10, 14, 18)])
    d.row("box", *[("box", c, c + 3, t, {"size": 9.5}) for c, t in zip(
        (0, 4, 8, 12, 16), ("**Руководство**\nсводные данные",
                            "**Производство**\nинженеры, технологи, операторы",
                            "**ТОиР**\nремонт оборудования",
                            "**Экономика и кадры**\nбухгалтерия, отдел кадров",
                            "**ИТ и ИБ**\nадминистрирование, контроль"))])
    d.row("box", ("text", 0, 19, "Внешние пользователи: подрядчики — временный доступ только к "
                                 "объектам договора", {"size": 9.5}))
    d.render(doc)
    caption_figure(doc, "Рисунок 1 – Субъекты доступа АС НПЗ")
    caption_table(doc, "Таблица 2 – Матрица доступа")
    roles = ["Руководство", "Инженеры, технологи", "Операторы", "ТОиР", "Бухгалтерия",
             "Отдел кадров", "ИТ-админ.", "Служба ИБ", "Подрядчики"]
    M = [
        ["Служебная информация, СЭД", "+", "+", "Ч", "+", "+", "+", "+", "+", "–"],
        ["Регламенты, режимные карты", "Ч", "+", "Ч*", "Ч", "–", "–", "–", "–", "Ч*"],
        ["Технологические параметры", "Ч", "Ч", "Ч*", "Ч*", "–", "–", "–", "–", "–"],
        ["Данные об оборудовании", "Ч", "Ч", "Ч*", "+", "Ч", "–", "–", "–", "Ч*"],
        ["Финансовая информация", "Ч", "–", "–", "–", "+", "–", "–", "–", "–"],
        ["Персональные данные", "Ч*", "–", "–", "–", "Ч*", "+", "–", "–", "–"],
        ["Коммерческая тайна", "+", "Ч*", "–", "–", "Ч*", "–", "–", "–", "–"],
        ["Настройки системы, журналы", "–", "–", "–", "–", "–", "–", "+", "Ч", "–"],
    ]
    t = data_table(doc, ["Информация"] + roles, M, widths=[5.2] + [1.26] * 9, size=10.5,
                   center_cols=tuple(range(1, 10)), rotate_header=tuple(range(1, 10)),
                   header_height=2.6)
    keep_together(t)
    P("Обозначения: «+» — чтение и запись; «Ч» — только чтение; «Ч*» — частично (только своя "
      "установка, свои договоры или данные для начисления зарплаты); «–» — доступа нет. "
      "Права назначаются по принципу минимальных привилегий; ИТ-администратор не имеет доступа "
      "к содержанию конфиденциальных данных.", size=12, indent=False)

    # ------------------------------------------------------------------ 4
    H1("4 Определение группы и класса защищённости")
    P("По РД Гостехкомиссии России (1992 г.) АС делятся на три группы: третья — один "
      "пользователь (классы 3Б, 3А); вторая — пользователи с одинаковыми правами (2Б, 2А); "
      "первая — многопользовательские АС с информацией разных уровней конфиденциальности, где не "
      "все пользователи имеют доступ ко всей информации (1Д, 1Г, 1В, 1Б, 1А).")
    P("В АС НПЗ работает около 1200 пользователей, их полномочия различны, обрабатывается "
      "информация разных уровней конфиденциальности, доступ ограничен матрицей. Следовательно, "
      "**АС НПЗ относится к первой группе**.")
    P("Классы 1В, 1Б, 1А предназначены для государственной тайны, поэтому выбор делается между "
      "1Д и 1Г. Класс 1Д контролирует только вход в систему. В АС НПЗ необходимо также "
      "разграничивать доступ к программам, файлам и записям баз данных (оператор и бухгалтер "
      "работают в одной системе с разными объектами) и регистрировать обращения к ним, например "
      "изменение задания на режим или рецептуры. Эти требования вводятся с **класса 1Г**. Если "
      "бы в АС обрабатывались секретные сведения, класс был бы не ниже 1В.")
    boxed(doc, "**Итог:** АС нефтеперерабатывающей компании относится к **I группе**; при "
               "отсутствии сведений, составляющих государственную тайну, принимается **класс "
               "защищённости 1Г**.")

    # ------------------------------------------------------------------ 5
    H1("5 Требования к АС класса 1Г")
    caption_table(doc, "Таблица 3 – Подсистемы защиты от НСД для АС НПЗ")
    data_table(doc, ["Подсистема", "Меры в АС НПЗ"], [
        ["Управление доступом", "Персональная учётная запись, пароль не менее 6 символов (в АС "
         "НПЗ — 8), идентификация АРМ, разграничение доступа к программам, файлам и записям по "
         "ролям; блокировка после неудачных попыток и при бездействии (рекомендуется)"],
        ["Регистрация и учёт", "Регистрация входа и выхода, неудачных попыток, запуска программ, "
         "доступа к защищаемым данным, изменения заданий на режим, выдачи печатных документов; "
         "учёт носителей; очистка освобождаемой памяти"],
        ["Криптографическая", "Для класса 1Г не обязательна. Рекомендуется: VPN и TLS по ГОСТ "
         "между площадками, шифрование резервных копий с ПДн, защищённое удалённое "
         "администрирование, учёт и смена ключей"],
        ["Обеспечение целостности", "Контроль целостности ПО и СЗИ, резервное копирование баз "
         "данных, восстановление после сбоя, физическая охрана серверных, периодическое "
         "тестирование средств защиты"],
    ], widths=[3.8, 12.7], size=11, bold_first_col=True)
    d = Diagram(20, size=9.5)
    steps = ["Пользователь", "Логин + пароль", "Идентификация", "Проверка полномочий",
             "Разрешение / отказ + запись в журнал"]
    items = []
    for i, s in enumerate(steps):
        c = i * 4
        items.append(("box", c, c + 2 if i < 4 else c + 3, s))
        if i < 4:
            items.append(("text", c + 3, c + 3, "►", {"size": 11}))
    d.row("box", *items)
    d.render(doc)
    caption_figure(doc, "Рисунок 2 – Управление доступом пользователя")

    # ------------------------------------------------------------------ 6
    H1("6 Общая схема АС НПЗ")
    d = Diagram(20, size=9.5)
    d.row("box", ("box", 6, 13, "**АС НПЗ**"))
    d.row("line", ("v", 10))
    d.row("line", ("h", 3, 17), *[("v", b) for b in (3, 10, 17)])
    d.row("box", ("box", 0, 5, "**Производственные данные**\nрежимы, учёт, качество, "
                               "оборудование"),
          ("box", 7, 12, "**Корпоративные данные**\nдокументы, договоры, коммерческая тайна"),
          ("box", 14, 19, "**Кадры и финансы**\nПДн, зарплата, бухгалтерия"))
    d.row("line", *[("v", b) for b in (3, 10, 17)])
    d.row("line", ("h", 3, 17), ("v", 10))
    d.row("arrow", ("arrow", 10))
    d.row("box", ("box", 6, 13, "**СЗИ от НСД**"))
    d.row("line", ("v", 10))
    d.row("line", ("h", 2, 18), *[("v", b) for b in (2, 7, 13, 18)])
    d.row("box", *[("box", a, b, t) for (a, b), t in zip(((0, 3), (5, 8), (11, 14), (16, 19)), (
        "Управление доступом", "Регистрация и учёт", "Криптография (рекомендуется)",
        "Целостность"))])
    d.row("line", *[("v", b) for b in (2, 7, 13, 18)])
    d.row("line", ("h", 2, 18), ("v", 10))
    d.row("arrow", ("arrow", 10))
    d.row("box", ("box", 6, 13, "**I ГРУППА · КЛАСС 1Г**", {"thick": True, "size": 11}))
    d.render(doc)
    caption_figure(doc, "Рисунок 3 – Общая схема АС НПЗ")

    # ------------------------------------------------------------------ 7
    H1("7 Заключение")
    P("АС нефтеперерабатывающей компании обрабатывает служебную, производственную, финансовую "
      "информацию, персональные данные и коммерческую тайну. Пользователи имеют разные "
      "полномочия, поэтому АС отнесена к **I группе** и для неё обоснован **класс 1Г** с "
      "подсистемами управления доступом, регистрации и учёта и обеспечения целостности. Защита "
      "информации на НПЗ важна не только для сохранения коммерческой тайны, но и для "
      "промышленной безопасности: искажение производственных данных может привести к "
      "нарушению технологии и аварии.")

    H1("Список источников")
    for i, r in enumerate([
        "РД Гостехкомиссии России «Автоматизированные системы. Защита от НСД к информации. "
        "Классификация автоматизированных систем и требования по защите информации» от "
        "30.03.1992 (учебная методика классификации).",
        "Федеральный закон от 27.07.2006 № 149-ФЗ «Об информации, информационных технологиях и "
        "о защите информации».",
        "Федеральный закон от 27.07.2006 № 152-ФЗ «О персональных данных».",
        "Федеральный закон от 29.07.2004 № 98-ФЗ «О коммерческой тайне».",
        "Федеральный закон от 26.07.2017 № 187-ФЗ «О безопасности критической информационной "
        "инфраструктуры Российской Федерации» (применяется к АСУ ТП, а не к классу от НСД).",
    ], start=1):
        P(f"{i} {r}")
    normalize(doc)
    doc.save(OUT)


if __name__ == "__main__":
    build()
    os.makedirs(os.path.join(HERE, "build"), exist_ok=True)
    subprocess.run(["soffice", "--headless", "--convert-to", "pdf", "--outdir",
                    os.path.join(HERE, "build"), OUT], check=True, capture_output=True, timeout=240)
    pdf = os.path.join(HERE, "build", "Oil_Refinery_Automated_System_Security.pdf")
    info = subprocess.run(["pdfinfo", pdf], capture_output=True, text=True).stdout
    print("pages:", re.search(r"Pages:\s+(\d+)", info).group(1))
